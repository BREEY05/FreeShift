import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { migrate } from '../src/db/index.ts';
import { seedDefaults } from '../src/db/seed-defaults.ts';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import type { FastifyInstance } from 'fastify';
import { buildApp } from '../src/app.ts';
import { closeDb, getDb, run } from '../src/db/index.ts';
let app:FastifyInstance;
const owner='owner@example.com', member='member@example.com', other='other@example.com';
function cookie(email:string):string {const token=createHash('sha256').update(email).digest('base64url');run("INSERT OR IGNORE INTO auth_account(email,role,created_at) VALUES(?,'member',?)",[email,Date.now()]);run('INSERT OR REPLACE INTO auth_session(token_hash,email,expires_at) VALUES(?,?,?)',[createHash('sha256').update(token).digest('hex'),email,Date.now()+86400000]);return 'freeshift_session='+token;}
function call(email:string,method:'GET'|'POST'|'PATCH'|'DELETE'|'PUT',url:string,payload?:object){return app.inject({method,url:'/api/v1'+url,headers:{cookie:cookie(email)},...(payload?{payload}:{})});}
beforeEach(()=>{closeDb();vi.stubEnv('DATABASE_PATH',':memory:');vi.stubEnv('AUTH_ENABLED','true');app=buildApp();});
afterEach(async()=>{await app.close();closeDb();vi.unstubAllEnvs();});
describe('organization tenancy',()=>{
 it('migrates legacy tables twice without losing schedule foreign keys',()=>{
   const {DatabaseSync}=createRequire(import.meta.url)('node:sqlite') as typeof import('node:sqlite');
   const db=new DatabaseSync(':memory:');
   let schema=readFileSync(new URL('../src/db/schema.sql',import.meta.url),'utf8');
   schema=schema.slice(0,schema.indexOf('CREATE TABLE IF NOT EXISTS organization'))+schema.slice(schema.indexOf('CREATE TABLE IF NOT EXISTS slot_template'));
   schema=schema.replaceAll('  org_id INTEGER NOT NULL REFERENCES organization(id) ON DELETE CASCADE,\n','').replaceAll(',\n  UNIQUE(org_id, name)','').replace(/name( +)TEXT( +)NOT NULL,/g,'name$1TEXT$2NOT NULL UNIQUE,');
   db.exec(schema);
   db.exec("INSERT INTO slot_template(name) VALUES('旧模板'); INSERT INTO time_slot(template_id,label,sort_order) VALUES(1,'旧时段',1); INSERT INTO semester(name,start_date,total_weeks,active_template_id,is_active) VALUES('旧学期','2026-09-01',20,1,1); INSERT INTO app_user(name) VALUES('旧用户'); INSERT INTO schedule(semester_id,user_id,weekday,slot_id,start_week,end_week) VALUES(1,1,1,1,1,2); INSERT INTO schedule_occurrence VALUES(1,1,1,1,1,1)");
   migrate(db);seedDefaults(db);migrate(db);seedDefaults(db);
   expect(db.prepare('PRAGMA foreign_key_check').all()).toEqual([]);
   expect(db.prepare('SELECT * FROM schedule_occurrence').all()).toHaveLength(1);
   expect(db.prepare('SELECT org_id FROM app_user WHERE id=1').get()).toMatchObject({org_id:1});
   expect(db.prepare('SELECT * FROM organization').all()).toHaveLength(1);
   expect(db.prepare("SELECT * FROM slot_template WHERE name='大学课表（秋）'").all()).toHaveLength(1);
   db.close();
 });
 it('creates organizations, approves joins and isolates users templates schedules and semesters',async()=>{
   expect((await call(owner,'GET','/org')).json().error.code).toBe('NO_ORG');
   const a=await call(owner,'POST','/org',{name:'组织A'});expect(a.statusCode).toBe(201);const orgA=a.json().data.org;
   expect(orgA.code).toMatch(/^[A-F0-9]{8}$/);
   expect((await call(member,'POST','/org/join',{code:orgA.code})).json().data.status).toBe('pending');
   expect((await call(member,'GET','/users')).json().error.code).toBe('PENDING_APPROVAL');
   expect((await call(owner,'GET','/org/requests')).json().data.requests).toHaveLength(1);
   expect((await call(owner,'POST','/org/requests/'+member+'/approve',{})).statusCode).toBe(200);
   expect((await call(member,'GET','/org')).json().data.org.id).toBe(orgA.id);
   expect((await call(member,'GET','/org/requests')).statusCode).toBe(403);
   expect((await call(member,'POST','/org/join',{code:orgA.code})).json().data.status).toBe('approved');
   await call(other,'POST','/org',{name:'组织B'});
   const ua=(await call(owner,'POST','/users',{name:'同名用户'})).json().data.user;
   const ub=(await call(other,'POST','/users',{name:'同名用户'})).json().data.user;
   expect((await call(owner,'GET','/users')).json().data.users.map((u:{id:number})=>u.id)).toEqual([ua.id]);
   expect((await call(owner,'GET','/users/'+ub.id)).statusCode).toBe(404);
   expect((await call(owner,'PATCH','/users/'+ub.id,{name:'越权'})).statusCode).toBe(404);
   const tb=(await call(other,'POST','/templates',{name:'私有模板'})).json().data.template;
   expect((await call(owner,'GET','/templates')).json().data.templates.some((t:{id:number})=>t.id===tb.id)).toBe(false);
   expect((await call(owner,'GET','/templates/'+tb.id)).statusCode).toBe(404);
   expect((await call(owner,'POST','/templates',{name:'非法克隆',cloneFrom:tb.id})).statusCode).toBe(404);
   expect((await call(owner,'POST','/semester',{name:'非法学期',startDate:'2026-09-01',totalWeeks:20,activeTemplateId:tb.id})).statusCode).toBe(404);
   const templates=(await call(other,'GET','/templates')).json().data.templates;
   const active=templates.find((t:{isActive:boolean})=>t.isActive);
   const slots=(await call(other,'GET','/templates/'+active.id)).json().data.slots;
   const sb=await call(other,'POST','/schedules',{userId:ub.id,weekday:1,slotId:slots[0].id,startWeek:1,endWeek:2});expect(sb.statusCode).toBe(201);
   const sid=sb.json().data.schedule.id;
   expect((await call(owner,'GET','/schedules')).json().data.schedules).toEqual([]);
   expect((await call(owner,'GET','/schedules/'+sid)).statusCode).toBe(404);
   expect((await call(owner,'DELETE','/schedules/'+sid)).statusCode).toBe(404);
   expect((await call(owner,'POST','/schedules',{userId:ua.id,weekday:1,slotId:slots[0].id,startWeek:1,endWeek:2})).statusCode).toBe(404);
   expect((await call(owner,'POST','/schedules/check',{userId:ua.id,weekday:1,slotIds:[slots[0].id],startWeek:1,endWeek:2})).statusCode).toBe(404);
   const autumn=templates.find((t:{name:string})=>t.name==='大学课表（秋）');
   const autumnSlots=(await call(other,'GET','/templates/'+autumn.id)).json().data.slots;
   expect(autumnSlots.map((s:{startTime:string,endTime:string,durationMin:number})=>[s.startTime,s.endTime,s.durationMin])).toEqual([['08:30','10:10',100],['10:30','12:10',100],['14:00','15:40',100],['16:00','17:40',100]]);
   expect(getDb().prepare('PRAGMA foreign_key_check').all()).toEqual([]);
 });
 it('rejects applications, removes members and protects the owner',async()=>{
   const org=(await call(owner,'POST','/org',{name:'审批组织'})).json().data.org;
   await call(member,'POST','/org/join',{code:org.code});
   expect((await call(owner,'POST','/org/requests/'+member+'/reject',{})).statusCode).toBe(200);
   expect((await call(member,'GET','/org')).json().error.code).toBe('NO_ORG');
   await call(member,'POST','/org/join',{code:org.code});await call(owner,'POST','/org/requests/'+member+'/approve',{});
   expect((await call(owner,'POST','/org/leave',{})).statusCode).toBe(409);
   expect((await call(owner,'DELETE','/org/members/'+owner)).statusCode).toBe(409);
   expect((await call(member,'POST','/org/leave',{})).statusCode).toBe(200);
   await call(member,'POST','/org/join',{code:org.code});await call(owner,'POST','/org/requests/'+member+'/approve',{});
   expect((await call(owner,'DELETE','/org/members/'+member)).statusCode).toBe(204);
   expect((await call(member,'GET','/users')).statusCode).toBe(404);
 });
});
